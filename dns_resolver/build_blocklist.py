def main() -> int:
    ap = argparse.ArgumentParser(description="Compile domain lists into a dnsmasq blocklist.")
    ap.add_argument("--block", action="append", default=[], metavar="FILE",
                    help="file of domains to block (repeatable)")
    ap.add_argument("--allow", action="append", default=[], metavar="FILE",
                    help="file of domains to always allow (repeatable)")
    ap.add_argument("--out", default=OUT, help=f"output hosts file (default {OUT})")
    ap.add_argument("--dry-run", action="store_true", help="print result, write nothing")
    ap.add_argument("--reload", action="store_true", help="SIGHUP dnsmasq to apply")
    args = ap.parse_args()

    blocked = set()
    for f in args.block:
        blocked |= read_domains(f)
    allowed = set()
    for f in args.allow:
        allowed |= read_domains(f)

    # Apply the AI hook, then subtract the allowlist (allow always wins).
    blocked |= {d for d in blocked if classify(d)}
    final = sorted(blocked - allowed)

    print(f"[*] {len(blocked)} blocked, {len(allowed)} allowed -> {len(final)} effective domains")
    if args.dry_run:
        for d in final[:50]:
            print("  ", d)
        if len(final) > 50:
            print(f"   ... and {len(final) - 50} more")
        print("[*] Dry run — nothing written.")
        return 0

    header = "# Generated by dns_resolver/build_blocklist.py — do not hand-edit.\n"
    body = "".join(f"0.0.0.0 {d}\n" for d in final)
    try:
        with open(args.out, "w") as fh:
            fh.write(header + body)
    except PermissionError:
        sys.exit(f"Cannot write {args.out} — re-run with sudo.")
    print(f"[*] Wrote {args.out}")

    # The resolver's service name is recorded by setup_resolver.sh.
    svc = "netlab-dnsmasq"
    try:
        with open("/etc/netlab/service") as fh:
            svc = fh.read().strip() or svc
    except OSError:
        pass

    if args.reload:
        try:
            subprocess.run(["systemctl", "reload", svc], check=True)
            print(f"[*] Reloaded {svc} — blocklist is live.")
        except (subprocess.CalledProcessError, FileNotFoundError):
            print(f"[!] Could not reload; run: sudo systemctl reload {svc}", file=sys.stderr)
    else:
        print(f"[*] Apply with: sudo systemctl reload {svc}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
