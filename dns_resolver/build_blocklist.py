#!/usr/bin/env python3
"""
build_blocklist.py — compile domain lists into a dnsmasq blocklist.

This is the enforcement half of your DNS filter. It reads plain lists of
domains (one per line) that you want BLOCKED, subtracts any you want ALLOWED,
and writes /etc/netlab/blocklist.hosts in the hosts format dnsmasq loads
(`0.0.0.0 domain`). A blocked domain then resolves to 0.0.0.0 for every device
on your LAN, so the site simply doesn't load.

Where your "AI DNS server" plugs in: right now categories come from static
list files (drop e.g. an adult-sites list in dns_resolver/lists/). Later,
replace/extend the `classify()` hook below with your model — return True to
block a domain, False to allow it — and this script becomes your model's
deploy step.

Lists are yours and can be large/sensitive, so keep them in dns_resolver/lists/
(git-ignored) rather than committing them.

Usage:
    # block everything in these files, keep allowlist exceptions:
    sudo python3 dns_resolver/build_blocklist.py \
        --block dns_resolver/lists/adult.txt --block dns_resolver/lists/ads.txt \
        --allow dns_resolver/lists/allow.txt --reload

    # dry run (print what would be blocked, write nothing):
    python3 dns_resolver/build_blocklist.py --block dns_resolver/lists/adult.txt --dry-run

    python3 dns_resolver/build_blocklist.py --help
"""
import argparse
import os
import re
import subprocess
import sys

OUT = "/etc/netlab/blocklist.hosts"
DOMAIN_RE = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$")


def read_domains(path):
    """Read a list file. Accepts plain domains or `0.0.0.0 domain` hosts lines."""
    out = set()
    try:
        with open(path, "r", errors="replace") as fh:
            for raw in fh:
                line = raw.strip().lower()
                if not line or line.startswith(("#", "!")):
                    continue
                parts = line.split()
                dom = parts[-1] if len(parts) > 1 else parts[0]  # tolerate hosts format
                dom = dom.rstrip(".")
                if DOMAIN_RE.match(dom):
                    out.add(dom)
    except FileNotFoundError:
        sys.exit(f"List not found: {path}")
    return out


